# name: (context, meaning, aliases) — the interface for the other modules.
ICONS = {n: (ctx, fn, al) for n, ctx, _, fn, _, al in CATALOG}
FAMILY = {n: fam for n, _, fam, *_ in CATALOG}
PICTURE = {n: pic for n, _, _, _, pic, _ in CATALOG}

# Not painted: start-here is made from the emblem.
PAINTED = [k for k in ICONS if k != "start-here"]

# Fixed bitmaps in all the sizes Dolphin and the panel ask for —
# KIconLoader did not take Type=Scalable reliably in the lab (NT Legacy, Warp).
SIZES = [16, 22, 24, 32, 48, 64, 96, 128, 256]


def describe():
    return "\n".join(f"- {k}: {v[1]}" for k, v in ICONS.items() if k in PAINTED)


def names():
    """All names the theme provides (pictures + aliases)."""
    out = []
    for n, (_, _, al) in ICONS.items():
        out += [n] + al
    return out
