"""Glyphs: the symbols the icons are composed of, on a 24 x 24 grid.

glyph(c, name, x, y, size, color) draws one into the box (x, y, size);
two-tone glyphs take a second colour from the world. Strokes are given
on the 24 grid; Canvas.group scales them with the glyph, and a glyph
drawn small (as an emblem) gets a heavier line so it still reads.

Each glyph is a function g_<name>(c, col); GLYPHS lists them. A glyph
names a thing or an idea, never a program.
"""
import math

GLYPHS = {}


def glyph(c, name, x, y, size, color=None, width=None):
    fn = GLYPHS[name]
    k = size / 24.0
    col = color or c["ink"]
    # Line weight on the 24 grid: so that it lands near 1.4 px at 48.
    lw = width if width is not None else max(1.6, 2.2 / max(k, 0.5)) if size < 24 else 1.8

    def draw(cv):
        cv._gw = lw
        fn(cv, col)
    c.group(f"translate({x:g} {y:g}) scale({k:g})", draw)


def reg(name):
    def deco(fn):
        GLYPHS[name] = fn
        return fn
    return deco


def W(c):
    return getattr(c, "_gw", 1.8)


def S(c, d, col, w=None):
    """A stroked path at the glyph's line weight (unscaled by Canvas)."""
    c.parts.append(f'<path d="{d}" fill="none" stroke="{col}" stroke-width="{(w or W(c)):g}" '
                   f'stroke-linecap="round" stroke-linejoin="round"/>')


def F(c, d, col, outline=None):
    o = f' stroke="{outline}" stroke-width="{W(c) * 0.6:g}" stroke-linejoin="round"' if outline else ""
    c.parts.append(f'<path d="{d}" fill="{col}"{o}/>')


def O(c, cx, cy, r, col, fill="none", w=None):
    c.parts.append(f'<circle cx="{cx:g}" cy="{cy:g}" r="{r:g}" fill="{fill}" stroke="{col}" '
                   f'stroke-width="{(w or W(c)):g}"/>')


def D(c, cx, cy, r, col):
    c.parts.append(f'<circle cx="{cx:g}" cy="{cy:g}" r="{r:g}" fill="{col}"/>')


